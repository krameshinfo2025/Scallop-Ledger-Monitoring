DROP TABLE IF EXISTS ledger_assets; 

CREATE TABLE ledger_assets( 
    currency VARCHAR(16) not null,
	display_scale smallint not null,
	display_name text         not null,
    kind         varchar(10)  not null,
    active       boolean      not null default true,
    created_at   timestamptz  not null default now(),
	updated_at   timestamptz  not null default now(),
	created_by   VARCHAR(36) not null default 'SCALLOP_SL',
	updated_by   VARCHAR(36) not null default 'SCALLOP_SL',
	version      smallint not null default 1,

    constraint currency_pk           primary key (currency),
    constraint currency_kind_valid   check (kind in ('FIAT', 'CRYPTO','OTHER')),
    constraint currency_scale_range  check (display_scale between 0 and 18),
    constraint currency_code_format  check (currency ~ '^[A-Z]{3,10}$')
	);
	
comment on table ledger_assets is
    'All currencies a holder may keep a wallet in. Hold-only: there is no conversion between them.';
comment on column ledger_assets.display_scale is
    'Meaningful decimal places. Amounts are stored as NUMERIC(38,18) regardless; this is the validation and presentation scale.';
